template <class T>
struct Codec;
template <class T>
Json pack(const T& v) {
  return Codec<T>::pack(v);
}
template <class T>
T unpack(const Json& v) {
  return Codec<T>::unpack(v);
}
template <class T>
struct Codec {
  static Json pack(const T& v) { return v; }
  static T unpack(const Json& v) { return v.get<T>(); }
};
