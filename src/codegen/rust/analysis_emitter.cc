std::string emitShapeInference(const core::Program& program,
                               const Names& names) {
  CodeWriter out;
  imports(out);
  out.open(
      "pub fn infer_shape(op: Op, operands: &[&[u64]], attrs: &OpAttrs) -> "
      "Inference<Vec<u64>>");
  signatureCheck(out);
  out.open(
      "let result: super::super::builtins::BuiltinResult<Vec<u64>> = match op");
  out.line("Op::Input => return Inference::Unknown,");
  out.line("Op::Literal => return Inference::Known(vec![]),");
  for (const auto& dialect : names.dialects)
    for (auto id : dialect.operations) {
      const auto& op = program.operations.at(id.value);
      out.line(operation(names, dialect, op) + " => " +
               (op.shape
                    ? "shape_" + std::to_string(id.value) + "(operands, attrs)"
                    : "return Inference::Unknown") +
               ",");
    }
  out.close(";");
  out.open("match result");
  out.line("Ok(shape) => Inference::Known(shape),");
  out.line("Err(error) => Inference::Invalid(error.message()),");
  out.close();
  out.close();
  for (const auto& dialect : names.dialects)
    for (auto id : dialect.operations) {
      const auto& op = program.operations.at(id.value);
      if (op.shape) evaluator(out, program, names, dialect, op);
    }
  return out.str();
}

std::string emitDTypeInference(const core::Program& program,
                               const Names& names) {
  CodeWriter out;
  imports(out);
  out.open(
      "pub fn infer_dtype(op: Op, operands: &[DType], attrs: &OpAttrs) -> "
      "Inference<DType>");
  signatureCheck(out);
  out.open("match op");
  out.line("Op::Input => Inference::Unknown,");
  out.line(
      "Op::Literal => { let OpAttrs::Literal { dtype, .. } = attrs else { "
      "unreachable!() }; "
      "dtype.map(Inference::Known).unwrap_or(Inference::Unknown) },");
  for (const auto& dialect : names.dialects)
    for (auto id : dialect.operations) {
      const auto& op = program.operations.at(id.value);
      std::string result = "Inference::Unknown";
      if (op.dtype)
        result = "match dtype_" + std::to_string(op.id.value) +
                 "(operands, attrs) { Ok(dtype) => Inference::Known(dtype), "
                 "Err(error) => Inference::Invalid(error.message()) }";
      out.line(operation(names, dialect, op) + " => " + result + ",");
    }
  out.close();
  out.close();
  for (const auto& dialect : names.dialects)
    for (auto id : dialect.operations) {
      const auto& op = program.operations.at(id.value);
      if (op.dtype) evaluator(out, program, names, dialect, op, true);
    }
  return out.str();
}
