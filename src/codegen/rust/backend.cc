#include "src/codegen/common/project_plan.h"
#include "src/codegen/rust/dialect_emitter.h"
#include "src/codegen/rust/graph_emitter.h"
#include "src/codegen/rust/metadata_emitter.h"
#include "src/codegen/rust/rule_emitter.h"
namespace tepl::codegen::rust {
GenerationResult generate(const executable::ExecutableProgram& executable,
                          const Options& options) {
  GenerationResult result;
  try {
    const auto& p = executable.ir();
    const auto project =
        planProject(p, options.rules_root, options.graphs_root);
    const Names names(p, project);
    result.files.push_back({"mod.rs",
                            "// Generated by TEPL.\n#![allow(dead_code, "
                            "unused_imports, unused_variables, unused_mut)]\n" +
                                emitProgram(p, names, executable.policy())});
    result.files.push_back({"metadata.rs", emitMetadata(p)});
    std::string dialects;
    for (const auto& d : names.dialects) {
      dialects += "pub mod " + d.module + ";\n";
      result.files.push_back(
          {"dialects/" + d.file_stem + ".rs", emitDialect(p, names, d)});
    }
    result.files.push_back({"dialects/mod.rs", dialects});
    std::string all =
        "pub fn all() -> ::tepl_runtime::EvalResult<Vec<super::Rewrite>> { "
        "Ok(vec![\n";
    for (const auto& m : names.modules) {
      result.files.push_back(
          {"rules/" + m.path + ".rs", emitRules(executable, names, m)});
      std::string path;
      for (std::size_t i = 0; i < m.path.size();) {
        auto end = m.path.find('/', i);
        if (end == std::string::npos) end = m.path.size();
        auto part = m.path.substr(i, end - i);
        path += Identifier::make(part, NameKind::kModule, {}).token + "::";
        i = end + 1;
      }
      for (auto id : m.rules)
        all += path + names.rule(id) + "::definition().build()?,\n";
    }
    all += "]) }\n";
    for (const auto& [path, children] : names.module_indexes) {
      std::string contents;
      for (const auto& child : children) contents += "pub mod " + child + ";\n";
      if (path.empty()) contents += all;
      result.files.push_back(
          {"rules/" + (path.empty() ? "" : path + "/") + "mod.rs", contents});
    }
    emitGraphs(p, names, project, result);
  } catch (const NameError& error) {
    result.files.clear();
    result.diagnostics.push_back({error.origin, error.what()});
  } catch (const std::exception& error) {
    result.files.clear();
    result.diagnostics.push_back({{}, error.what()});
  }
  return result;
}
}  // namespace tepl::codegen::rust
